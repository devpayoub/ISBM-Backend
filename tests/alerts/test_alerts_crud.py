def test_declare_sets_priority_score(admin_client, make_machine, make_category):
    from apps.alerts.models import Alert
    machine = make_machine()
    cat = make_category()
    payload = _declare_payload(machine, cat, severity="CRITICAL")
    resp = admin_client.post(ALERTS_URL, payload, format="json")
    assert resp.status_code == 201
    # priority_score is computed in Alert.save() (alerts/models.py). The create
    # serializer doesn't return priority_score, so verify via DB or retrieve.
    alert = Alert.objects.filter(machine=machine, severity="CRITICAL").latest("created_at")
    # severity weight 1000 + open bonus 1000 = 2000 for CRITICAL+OPEN
    assert alert.priority_score == 2000
    # And the retrieve endpoint exposes it too
    detail = admin_client.get(f"{ALERTS_URL}/{alert.pk}").json()
    assert detail["priority_score"] == 2000


