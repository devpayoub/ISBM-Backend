"""Tests for /api/v1/alerts CRUD (POST declare, GET list, GET retrieve, DELETE).

Permission layout (apps/alerts/views.py):
- AlertViewSet.permission_classes = (IsAuthenticated,)        [viewset-level]
- perform_create blocks non-authorized roles inline:
    allowed_roles = ADMIN, MANAGER, CONTROLLER, MAINTENANCE   [views.py:53]
  (OPERATOR is rejected); no on-duty enforcement at the moment
  (the if-block at views.py:55 ends with `pass` — see test_offduty_*).
- destroy has NO explicit decorator -> falls back to viewset permission only
  (= IsAuthenticated). So ANY authenticated role may currently DELETE any alert.
  This is bug #5 — captured with @pytest.mark.xfail.
"""
import pytest

from apps.alerts.models import Alert, AlertStatus, Severity

pytestmark = pytest.mark.django_db

ALERTS_URL = "/api/v1/alerts"


def _declare_payload(machine, category, severity="MAJOR", worker="T. Operator"):
    return {
        "machine": machine.pk,
        "category": category.pk,
        "title": "Test alert",
        "description": "auto-generated by tests",
        "severity": severity,
        "worker_name": worker,
        "shift": "MORNING",
        "downtime_min": 5,
        "bottles_lost": 10,
    }


# ---------------------------------------------------------------------------
# List / retrieve — every authenticated role
# ---------------------------------------------------------------------------
@pytest.mark.parametrize("role", ["ADMIN", "MANAGER", "CONTROLLER", "MAINTENANCE", "OPERATOR"])
def test_any_role_lists_alerts(api_as, role, make_alert):
    make_alert()
    resp = api_as(role).get(ALERTS_URL)
    assert resp.status_code == 200
    rows = resp.json().get("results") or resp.json()
    assert len(rows) >= 1


@pytest.mark.parametrize("role", ["ADMIN", "MANAGER", "CONTROLLER", "MAINTENANCE", "OPERATOR"])
def test_any_role_can_retrieve_single_alert(api_as, role, make_alert):
    a = make_alert()
    resp = api_as(role).get(f"{ALERTS_URL}/{a.pk}")
    assert resp.status_code == 200
    assert resp.json()["id"] == a.pk


def test_unauthenticated_list_401(api):
    assert api.get(ALERTS_URL).status_code == 401


# ---------------------------------------------------------------------------
# Declare (POST) — role gating in perform_create
# ---------------------------------------------------------------------------
@pytest.mark.parametrize("role", ["ADMIN", "MANAGER", "CONTROLLER", "MAINTENANCE"])
def test_authorized_roles_can_declare(api_as, role, make_machine, make_category):
    from apps.alerts.models import Alert
    machine = make_machine()
    cat = make_category()
    payload = _declare_payload(machine, cat)
    # The role (CONTROLLER etc) is set on a user auto-created by api_as; we need
    # to know which User is "me" to compare reported_by.
    client = api_as(role)
    payload = _declare_payload(machine, cat)
    resp = client.post(ALERTS_URL, payload, format="json")
    assert resp.status_code == 201, resp.content
    # The create response uses AlertCreateSerializer which echoes the input fields
    # only (no id, no status, no reported_by). Verify state via the DB.
    body = resp.json()
    assert body["severity"] == "MAJOR"
    alert = Alert.objects.filter(machine=machine, title="Test alert").latest("created_at")
    assert alert.status == "OPEN"
    assert alert.reported_by_id == client.user.pk


def test_operator_cannot_declare(operator_client, make_machine, make_category):
    payload = _declare_payload(make_machine(), make_category())
    resp = operator_client.post(ALERTS_URL, payload, format="json")
    assert resp.status_code == 403
    assert "Rôle insuffisant" in resp.json()["detail"]


