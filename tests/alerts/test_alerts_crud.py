def test_filter_by_status(admin_client, make_alert):
    make_alert(status=AlertStatus.OPEN)
    make_alert(status=AlertStatus.RESOLVED)
    resp = admin_client.get(f"{ALERTS_URL}?status=RESOLVED")
    assert resp.status_code == 200
    rows = resp.json().get("results") or resp.json()
    assert all(r["status"] == "RESOLVED" for r in rows)


def test_filter_by_severity(admin_client, make_alert):
    make_alert(severity=Severity.CRITICAL)
    make_alert(severity=Severity.MINOR)
    resp = admin_client.get(f"{ALERTS_URL}?severity=CRITICAL")
    rows = resp.json().get("results") or resp.json()
    assert rows and all(r["severity"] == "CRITICAL" for r in rows)


